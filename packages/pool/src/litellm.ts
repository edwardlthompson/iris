import type { Pool } from "@iris/protocol";

/** Generate LiteLLM YAML bound to 127.0.0.1 only — keys stay in LiteLLM, not Iris. */
export function generateLiteLLMConfig(pools: Pool[], listen = "127.0.0.1:4000"): string {
  if (!listen.startsWith("127.0.0.1")) {
    throw new Error("LiteLLM must bind 127.0.0.1 only");
  }
  const lines = [
    `# Generated by @iris/pool (chrysaor) — do not store pool keys in Iris`,
    `general_settings:`,
    `  master_key: os.environ/LITELLM_MASTER_KEY`,
    `litellm_settings:`,
    `  drop_params: true`,
    `model_list:`,
  ];
  for (const p of pools) {
    lines.push(`  - model_name: ${p.id}/*`);
    lines.push(`    litellm_params:`);
    lines.push(`      model: openai/${p.id}`);
    lines.push(`      api_base: ${p.baseUrl}`);
    lines.push(`      api_key: os.environ/${envKey(p.auth.keyRef)}`);
  }
  lines.push(`server:`);
  lines.push(`  host: 127.0.0.1`);
  lines.push(`  port: ${listen.split(":")[1] ?? "4000"}`);
  return lines.join("\n") + "\n";
}

function envKey(keyRef: string): string {
  return keyRef.replace(/[^A-Za-z0-9_]/g, "_").toUpperCase();
}
